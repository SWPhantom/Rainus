// SD-card storage, from filesystem requests down to the physical wires.
//
// Big picture:
//   log.c -> FatFs (files/directories) -> disk_read/disk_write (512-byte sectors)
//         -> SD commands -> SPI1 (the chip's byte-transfer hardware) -> card.
// This file knows sectors, not filenames or CSV rows. FatFs requires the
// disk_* function names/signatures below; our private helpers use plain names.
//
// SPI means Serial Peripheral Interface. Four wires connect this board to
// its ONE fixed card socket; callers do not choose between multiple cards:
//   CS   = chip select: LOW (~0 V) tells the card to listen; HIGH (~3.3 V)
//          ends the transaction. This does NOT switch off the card's power.
//   SCK  = serial clock: the board generates pulses that advance the bits.
//   MOSI = master out, slave in: data from the board to the card.
//   MISO = master in, slave out: data from the card to the board.
// A byte transfer makes eight clock pulses and moves one bit in EACH direction
// per pulse. Even to read, we must send a byte to make those pulses. We send
// 0xFF (eight 1 bits) when the outgoing data has no other meaning.
//
// SD (Secure Digital) cards have a specified command/response protocol. For
// example, CMD17 means command number 17, "read one sector". These numbers
// are card-protocol values, not arbitrary application codes. We support SD
// version 2+ cards: standard-capacity (SDSC), high-capacity (SDHC), and
// extended-capacity (SDXC). Older SD v1 and MMC cards are not initialized.
//
// Failures return through FatFs to Rainus: mount/startup error 3, file error 5.
// The waits let the card finish real work; their limits let a failed/absent
// card report an error rather than wait forever. There is no recovery loop
// here that retries an already partially written log batch.
#include "ch32fun.h"
#include "fatfs/diskio.h"

#define SD_CHIP_SELECT_PIN   PA3 // LOW selects the card; HIGH releases it.
#define SD_CLOCK_PIN         PA5 // Clock pulses generated by the board.
#define SD_CARD_TO_BOARD_PIN PA6 // Card -> board data.
#define SD_BOARD_TO_CARD_PIN PA7 // Board -> card data.

// Sizes defined by the SD protocol, except the explicitly noted format hint.
enum {
    SD_DRIVE_NUMBER = 0, // FatFs numbers drives; Rainus has just drive zero.
    SD_SECTOR_BYTES = 512, // A sector is the unit read/written on the card.
    // Most commands return a one-byte status, called "R1" in the SD spec.
    // Voltage checking (CMD8) and power/address information (CMD58) then
    // return FOUR more bytes. Those bytes must also be read, not left behind.
    SD_EXTRA_RESPONSE_BYTES = 4,
    // Each sector's data is followed by a two-byte CRC (Cyclic Redundancy
    // Check, a checksum for transmission errors). We transfer these bytes
    // to finish the packet, but do not validate read-data CRCs in this driver.
    SD_DATA_CHECKSUM_BYTES = 2,
    // Flash memory is erased internally in groups of sectors. FatFs can ask
    // the size of such a group when formatting. We do not query the card's
    // actual group size; 1 is a placeholder, NOT a measured erase size.
    // Rainus disables FatFs's formatting feature, so this hint is not used.
    SD_FORMATTING_ERASE_GROUP_HINT = 1
};

// Values sent to the card. "CMD" is the specification's name for a command;
// "ACMD" is an extended/application command, introduced by sending CMD55.
enum {
    SD_COMMAND_RESET_TO_SPI = 0, // CMD0: enter SPI mode and reset to idle.
    SD_COMMAND_CHECK_VOLTAGE = 8, // CMD8: check voltage support and echo a pattern.
    SD_COMMAND_SET_SECTOR_SIZE = 16, // CMD16: use 512 bytes on byte-addressed cards.
    SD_COMMAND_READ_ONE_SECTOR = 17, // CMD17: fetch one sector's contents.
    SD_COMMAND_WRITE_ONE_SECTOR = 24, // CMD24: send one sector's contents.
    SD_COMMAND_START_INITIALIZATION = 41, // ACMD41: start/check card initialization.
    SD_COMMAND_PREFIX_FOR_EXTENDED_COMMAND = 55, // CMD55: next command is extended.
    // CMD58 reads the Operating Conditions Register (OCR): a card information
    // word containing voltage and address-mode bits, unrelated to text recognition.
    SD_COMMAND_READ_POWER_AND_ADDRESSING = 58
};

// Packet fields and bit masks defined by the SD protocol.
enum {
    SD_OUTGOING_ONES = 0xff, // Eight 1 bits; supplies clock pulses for a read.
    SD_NO_RESPONSE = 0xff, // Our failure result; never a valid R1 status.
    SD_COMMAND_PREFIX = 0x40, // The first byte is bits 01 + a six-bit command number.
    SD_RESPONSE_START_BIT_MASK = 0x80, // R1 status always has its highest bit = 0.
    SD_STATUS_READY = 0x00, // No status/error bits set.
    SD_STATUS_INITIALIZING = 0x01, // Idle bit set: card not initialized yet.
    SD_DATA_START_BYTE = 0xfe, // Announces that 512 data bytes follow.
    SD_WRITE_RESPONSE_MASK = 0x1f, // Only the low five bits describe acceptance.
    SD_WRITE_ACCEPTED = 0x05, // Low bits 00101: card accepted the data packet.
    // A command ends in a seven-bit CRC checksum and a final 1 bit. These
    // precomputed bytes are valid for our fixed CMD0/CMD8 arguments below.
    SD_RESET_COMMAND_CHECKSUM = 0x95,
    SD_VOLTAGE_COMMAND_CHECKSUM = 0x87,
    SD_SUPPORTED_VOLTAGE_CODE = 1, // CMD8 code for a 2.7-3.6 V card supply.
    SD_VOLTAGE_TEST_PATTERN = 0xaa, // Card must echo this byte unchanged.
    SD_VOLTAGE_TEST_ARGUMENT = (SD_SUPPORTED_VOLTAGE_CODE << 8) | SD_VOLTAGE_TEST_PATTERN,
    SD_VOLTAGE_RESPONSE_CODE_INDEX = 2, // Positions within the four extra bytes.
    SD_VOLTAGE_RESPONSE_PATTERN_INDEX = 3,
    SD_BOARD_SUPPORTS_HIGH_CAPACITY = 0x40000000, // ACMD41 argument, bit 30.
    SD_CARD_USES_SECTOR_ADDRESSES = 0x40 // CMD58's first byte, bit 6 (word bit 30).
};

// Driver choices: how often/how long to ask the hardware again. These keep
// the timings from our working board tests. A retry means one more attempt
// after the first one, not a strict elapsed-time deadline: transfers and
// input interrupts take extra time beyond the explicit millisecond delays.
enum {
    SD_POLL_DELAY_MS = 1,
    SD_TRANSACTION_BUSY_RETRIES = 500, // Up to 501 busy checks, including first.
    SD_PROGRAMMING_BUSY_RETRIES = 1000, // Up to 1001 checks after writing data.
    SD_COMMAND_RESPONSE_BYTE_LIMIT = 10,
    SD_READ_START_BYTE_ATTEMPTS = 250,
    SD_POWER_SETTLE_MS = 100,
    // Ten bytes make 80 clock pulses with chip select and outgoing data HIGH.
    // The SD startup sequence requires at least 74 pulses before CMD0.
    SD_STARTUP_CLOCK_BYTES = 10,
    SD_RESET_ATTEMPTS = 100,
    SD_RESET_RETRY_DELAY_MS = 10,
    SD_INIT_ATTEMPTS = 1000
};

static DSTATUS disk_state = STA_NOINIT;
static int card_uses_sector_addresses;

// Send outgoing and return the card's simultaneous reply (one byte each).
// SPI1->... refers to hardware registers, not ordinary variables. STATR is
// the status register; TXE (Transmit Empty) means the send buffer has room.
// Writing DATAR (data register) starts the eight clock pulses. RXNE (Receive
// Not Empty) means the received byte is now available to read from DATAR.
// These short hardware waits are not software locks or periodic sleep wakes.
// They remain unbounded here; the card-level waits below have failure limits.
static uint8_t spi_send_and_receive_byte(uint8_t outgoing)
{
    while (!(SPI1->STATR & SPI_STATR_TXE)) {}
    SPI1->DATAR = outgoing;
    while (!(SPI1->STATR & SPI_STATR_RXNE)) {}
    return SPI1->DATAR;
}

// Finish with our one card. Raising its chip-select wire tells it to stop
// listening and release its data-output wire so it no longer drives that wire.
// Send one extra byte (eight clock pulses) to finish that release sequence.
// This leaves the card powered; it is not a low-power or power-off command.
static void sd_end_transaction(void)
{
    funDigitalWrite(SD_CHIP_SELECT_PIN, FUN_HIGH);
    spi_send_and_receive_byte(SD_OUTGOING_ONES);
}

// Ask whether the selected card has finished its previous internal operation.
// Its chip-select wire must already be LOW. While busy, the card sends zero
// bits on its output wire; when ready it sends all ones (0xFF). Sending 0xFF
// ourselves supplies the eight clock pulses needed to read that answer.
// Return 1 for ready, 0 if the initial attempt plus retries all find it busy.
// Each busy answer is followed by 1 ms delay, including the final failed one.
static int sd_wait_until_not_busy(unsigned retries_remaining)
{
    for (;;) {
        if (spi_send_and_receive_byte(SD_OUTGOING_ONES) == SD_OUTGOING_ONES) return 1;
        Delay_Ms(SD_POLL_DELAY_MS);
        if (retries_remaining == 0) return 0;
        --retries_remaining;
    }
}

// Begin talking to our fixed socket: drive chip select LOW, exchange one
// fill byte, then wait for the card to stop being busy. Return 1 with the
// transaction still open, or 0 after ending it on failure. No card argument
// is needed because there is only one socket and one chip-select pin.
static int sd_begin_transaction(void)
{
    funDigitalWrite(SD_CHIP_SELECT_PIN, FUN_LOW);
    spi_send_and_receive_byte(SD_OUTGOING_ONES);
    if (sd_wait_until_not_busy(SD_TRANSACTION_BUSY_RETRIES)) return 1;
    sd_end_transaction();
    return 0;
}

// Send a card command: [command number, four argument bytes, checksum].
// Return its one-byte R1 status, or SD_NO_RESPONSE if no valid status arrives.
// A zero status means ready, 1 means still initializing; other bits indicate
// card errors. Each caller checks the status appropriate for its command.
// After sending, leave chip select LOW so the caller can read extra response
// bytes or move sector data. Caller must end the transaction when finished.
static uint8_t sd_send_command(uint8_t command_index, uint32_t argument)
{
    sd_end_transaction();
    if (command_index == SD_COMMAND_RESET_TO_SPI) {
        // CMD0 switches a newly powered card into SPI mode. Waiting for SPI
        // readiness BEFORE that command caused our SanDisk cold-start failure.
        funDigitalWrite(SD_CHIP_SELECT_PIN, FUN_LOW);
        spi_send_and_receive_byte(SD_OUTGOING_ONES);
    } else if (!sd_begin_transaction()) {
        return SD_NO_RESPONSE;
    }

    spi_send_and_receive_byte(SD_COMMAND_PREFIX | command_index);
    // Serialize the 32-bit argument one byte at a time, most significant first.
    spi_send_and_receive_byte(argument >> 24);
    spi_send_and_receive_byte(argument >> 16);
    spi_send_and_receive_byte(argument >> 8);
    spi_send_and_receive_byte(argument);

    // The SPI protocol normally leaves command CRC checking disabled. CMD0
    // and CMD8 still require the valid checksum/final-bit bytes for the
    // specific arguments used here; arbitrary arguments would need a new CRC.
    uint8_t crc = SD_OUTGOING_ONES;
    if (command_index == SD_COMMAND_RESET_TO_SPI) crc = SD_RESET_COMMAND_CHECKSUM;
    else if (command_index == SD_COMMAND_CHECK_VOLTAGE) crc = SD_VOLTAGE_COMMAND_CHECKSUM;
    spi_send_and_receive_byte(crc);

    // Send up to ten fill bytes to read the reply. A highest bit of zero
    // identifies a status byte rather than the all-ones "no reply yet" value.
    for (unsigned poll = 0; poll < SD_COMMAND_RESPONSE_BYTE_LIMIT; ++poll) {
        uint8_t response = spi_send_and_receive_byte(SD_OUTGOING_ONES);
        if (!(response & SD_RESPONSE_START_BIT_MASK)) return response;
    }
    return SD_NO_RESPONSE;
}

// Convert FatFs's sector number to the address unit expected by this card.
// Standard-capacity cards count BYTES; high/extended-capacity cards count
// 512-byte SECTORS. For example, sector 2 is address 1024 or 2 respectively.
static uint32_t sd_command_address(LBA_t sector)
{
    return card_uses_sector_addresses ? sector : sector * SD_SECTOR_BYTES;
}

// FatFs startup entry point. Configure the pins/byte-transfer hardware, then
// reset the card, check voltage support, initialize, and learn its addressing.
// Return 0 on success or STA_NOINIT (Not Initialized) on any failed step.
// No files or sectors are written by this initialization sequence.
DSTATUS disk_initialize(BYTE drive)
{
    if (drive != SD_DRIVE_NUMBER) return STA_NOINIT;
    disk_state = STA_NOINIT;
    card_uses_sector_addresses = 0;
    // RCC is the Reset and Clock Control hardware. Enable SPI1's clock so
    // its registers/byte-transfer engine work; funGpioInitAll enabled the pins.
    RCC->APB2PCENR |= RCC_APB2Periph_SPI1;
    funDigitalWrite(SD_CHIP_SELECT_PIN, FUN_HIGH);
    funPinMode(SD_CHIP_SELECT_PIN, GPIO_CFGLR_OUT_10Mhz_PP);
    funPinMode(SD_CLOCK_PIN, GPIO_CFGLR_OUT_10Mhz_AF_PP);
    funPinMode(SD_CARD_TO_BOARD_PIN, GPIO_CFGLR_IN_FLOAT);
    funPinMode(SD_BOARD_TO_CARD_PIN, GPIO_CFGLR_OUT_10Mhz_AF_PP);
    // The board generates the clock (master), transferring eight bits/byte.
    // Mode 0 means the clock rests LOW and receivers sample each rising edge.
    // Pin modes ending AF_PP route the SPI hardware to the output pin
    // (Alternate Function, Push-Pull). IN_FLOAT makes the card's output pin
    // an input on our side. OUT_10Mhz is a pin drive-speed setting, not the
    // SPI clock frequency; the divider below chooses that separately.
    // The library's required register names below mean: MSTR=master,
    // SSM=software select management, SSI=internal select HIGH, SPE=SPI enabled.
    // Our PA3 output controls the actual card selection; the SPI hardware's
    // separate select input (NSS) is therefore kept internally inactive.
    const uint16_t spi_config = SPI_CTLR1_MSTR | SPI_CTLR1_SSM | SPI_CTLR1_SSI | SPI_CTLR1_SPE;
    // Keep initialization within the SD card's 100-400 kHz range.
#if RAINUS_DEBUG_USB
    const uint16_t init_speed = SPI_CTLR1_BR; // 48 MHz / 256 = 187.5 kHz.
#else
    const uint16_t init_speed = SPI_CTLR1_BR_2; // 8 MHz / 32 = 250 kHz.
#endif
    SPI1->CTLR1 = spi_config | init_speed;
    Delay_Ms(SD_POWER_SETTLE_MS);
    for (unsigned i = 0; i < SD_STARTUP_CLOCK_BYTES; ++i)
        spi_send_and_receive_byte(SD_OUTGOING_ONES);

    // Stage 1: reset into SPI mode. The bounded retries fixed the remaining
    // SanDisk cold-start issue; a successful reset returns the IDLE status.
    int reset_ok = 0;
    for (unsigned attempt = 0; attempt < SD_RESET_ATTEMPTS; ++attempt) {
        if (sd_send_command(SD_COMMAND_RESET_TO_SPI, 0) == SD_STATUS_INITIALIZING) {
            reset_ok = 1;
            break;
        }
        Delay_Ms(SD_RESET_RETRY_DELAY_MS);
    }
    if (!reset_ok) goto done;

    // Stage 2: check that the card supports our voltage and correctly echoes
    // the test pattern. CMD8 returns status plus four more response bytes.
    if (sd_send_command(SD_COMMAND_CHECK_VOLTAGE, SD_VOLTAGE_TEST_ARGUMENT) != SD_STATUS_INITIALIZING) goto done;
    uint8_t interface_response[SD_EXTRA_RESPONSE_BYTES];
    for (unsigned i = 0; i < SD_EXTRA_RESPONSE_BYTES; ++i)
        interface_response[i] = spi_send_and_receive_byte(SD_OUTGOING_ONES);
    if (interface_response[SD_VOLTAGE_RESPONSE_CODE_INDEX] != SD_SUPPORTED_VOLTAGE_CODE ||
        interface_response[SD_VOLTAGE_RESPONSE_PATTERN_INDEX] != SD_VOLTAGE_TEST_PATTERN) goto done;

    // Stage 3: start initialization, declaring support for high-capacity cards.
    // Each attempt sends CMD55 then the extended command ACMD41. A status
    // of zero means done; 1 means still initializing; other bits mean errors.
    int initialized = 0;
    for (unsigned attempt = 0; attempt < SD_INIT_ATTEMPTS; ++attempt) {
        if (sd_send_command(SD_COMMAND_PREFIX_FOR_EXTENDED_COMMAND, 0) > SD_STATUS_INITIALIZING) break;
        if (sd_send_command(SD_COMMAND_START_INITIALIZATION, SD_BOARD_SUPPORTS_HIGH_CAPACITY) == SD_STATUS_READY) {
            initialized = 1;
            break;
        }
        Delay_Ms(SD_POLL_DELAY_MS);
    }
    if (!initialized) goto done;

    // Stage 4: read the card's power/address information (CMD58). We use only
    // the address-mode bit in its first byte, but must read all four bytes.
    // For byte-addressed cards, also set the sector size to 512 (CMD16).
    if (sd_send_command(SD_COMMAND_READ_POWER_AND_ADDRESSING, 0) != SD_STATUS_READY) goto done;
    uint8_t power_info_first_byte = spi_send_and_receive_byte(SD_OUTGOING_ONES);
    for (unsigned i = 0; i < SD_EXTRA_RESPONSE_BYTES - 1; ++i)
        spi_send_and_receive_byte(SD_OUTGOING_ONES);
    card_uses_sector_addresses = !!(power_info_first_byte & SD_CARD_USES_SECTOR_ADDRESSES);
    if (!card_uses_sector_addresses) {
        if (sd_send_command(SD_COMMAND_SET_SECTOR_SIZE, SD_SECTOR_BYTES) != SD_STATUS_READY) goto done;
    }
    disk_state = 0; // No FatFs status flags: initialization succeeded.
    // Preserve the tested transfer speed: 250 kHz field / 1.5 MHz USB debug.
    SPI1->CTLR1 = spi_config | SPI_CTLR1_BR_2;
done:
    sd_end_transaction();
    return disk_state;
}

// Report our last initialization result; this does not probe for card removal.
DSTATUS disk_status(BYTE drive)
{
    return drive == SD_DRIVE_NUMBER ? disk_state : STA_NOINIT;
}

// Read count consecutive sectors into buffer (caller provides count * 512
// bytes of space), starting at sector. Each command reads ONE sector.
// For each one: command -> start byte -> 512 data bytes -> two checksum bytes.
// Return RES_OK on success, RES_NOTRDY for an invalid drive/not initialized/
// zero count, or RES_ERROR for a command/data failure. Results reach Rainus
// through FatFs. On failure, part of the buffer may already have been filled.
DRESULT disk_read(BYTE drive, BYTE *buffer, LBA_t sector, UINT count)
{
    if (drive != SD_DRIVE_NUMBER || (disk_state & STA_NOINIT) || count == 0) return RES_NOTRDY;
    while (count > 0) {
        if (sd_send_command(SD_COMMAND_READ_ONE_SECTOR, sd_command_address(sector)) != SD_STATUS_READY)
            goto fail;
        uint8_t token = SD_OUTGOING_ONES;
        for (unsigned poll = 0; poll < SD_READ_START_BYTE_ATTEMPTS; ++poll) {
            token = spi_send_and_receive_byte(SD_OUTGOING_ONES);
            if (token != SD_OUTGOING_ONES) break;
            Delay_Ms(SD_POLL_DELAY_MS);
        }
        if (token != SD_DATA_START_BYTE) goto fail;
        for (unsigned i = 0; i < SD_SECTOR_BYTES; ++i)
            *buffer++ = spi_send_and_receive_byte(SD_OUTGOING_ONES);
        // Consume the trailing CRC even though this driver does not verify it.
        for (unsigned i = 0; i < SD_DATA_CHECKSUM_BYTES; ++i)
            spi_send_and_receive_byte(SD_OUTGOING_ONES);
        ++sector;
        --count;
    }
    sd_end_transaction();
    return RES_OK;
fail:
    sd_end_transaction();
    return RES_ERROR;
}

// Write count consecutive sectors from buffer (count * 512 bytes).
// For each one: command -> start byte -> 512 bytes -> checksum placeholders
// -> acceptance reply -> wait until internal flash programming finishes.
// Same return meanings as disk_read. Failure may follow partial progress;
// Rainus stops rather than automatically repeating a partially saved batch.
DRESULT disk_write(BYTE drive, const BYTE *buffer, LBA_t sector, UINT count)
{
    if (drive != SD_DRIVE_NUMBER || (disk_state & STA_NOINIT) || count == 0) return RES_NOTRDY;
    while (count > 0) {
        if (sd_send_command(SD_COMMAND_WRITE_ONE_SECTOR, sd_command_address(sector)) != SD_STATUS_READY)
            goto fail;
        spi_send_and_receive_byte(SD_DATA_START_BYTE);
        for (unsigned i = 0; i < SD_SECTOR_BYTES; ++i) spi_send_and_receive_byte(*buffer++);
        // Two placeholder checksum bytes are allowed because data CRC checking
        // is disabled. They still occupy two required positions in the packet.
        for (unsigned i = 0; i < SD_DATA_CHECKSUM_BYTES; ++i)
            spi_send_and_receive_byte(SD_OUTGOING_ONES);
        uint8_t response = spi_send_and_receive_byte(SD_OUTGOING_ONES);
        if ((response & SD_WRITE_RESPONSE_MASK) != SD_WRITE_ACCEPTED) goto fail;
        // Accepted means the packet arrived; wait for internal programming too.
        if (!sd_wait_until_not_busy(SD_PROGRAMMING_BUSY_RETRIES)) goto fail;
        ++sector;
        --count;
    }
    sd_end_transaction();
    return RES_OK;
fail:
    sd_end_transaction();
    return RES_ERROR;
}

// FatFs also calls this for non-read/write requests. CTRL_SYNC asks whether
// the card has finished programming; FatFs has already sent its cached data.
// Size requests place their answer in the caller's correctly typed buffer.
// Unsupported requests return RES_PARERR (parameter/request not supported).
DRESULT disk_ioctl(BYTE drive, BYTE cmd, void *buffer)
{
    if (drive != SD_DRIVE_NUMBER || (disk_state & STA_NOINIT)) return RES_NOTRDY;
    switch (cmd) {
    case CTRL_SYNC:
        if (!sd_begin_transaction()) return RES_ERROR;
        sd_end_transaction();
        return RES_OK;
    case GET_SECTOR_SIZE:
        *(WORD *)buffer = SD_SECTOR_BYTES;
        return RES_OK;
    case GET_BLOCK_SIZE:
        // Placeholder only; see SD_FORMATTING_ERASE_GROUP_HINT above.
        *(DWORD *)buffer = SD_FORMATTING_ERASE_GROUP_HINT;
        return RES_OK;
    default:
        return RES_PARERR;
    }
}
